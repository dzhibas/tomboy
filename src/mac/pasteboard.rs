//! The general pasteboard through AppKit: what `pbcopy`/`pbpaste` can't do — images, copied
//! files, and the markers password managers put on what they copy.

use objc2::rc::{Retained, autoreleasepool};
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{
    NSBitmapImageFileType, NSBitmapImageRep, NSPasteboard, NSPasteboardItem, NSPasteboardType,
    NSPasteboardTypeFileURL, NSPasteboardTypePNG, NSPasteboardTypeString, NSPasteboardTypeTIFF,
    NSPasteboardWriting,
};
use objc2_foundation::{NSArray, NSData, NSDictionary, NSString};

/// One copy, as the clipboard history records it.
#[derive(Debug, PartialEq)]
pub enum Copied {
    Text(String),
    Png(Vec<u8>),
    /// `file:///…` URLs, one per copied file (the shape of Linux's `text/uri-list`).
    Files(Vec<String>),
}

/// Types apps put on copies that shouldn't be kept (nspasteboard.org; 1Password's own).
const PRIVATE: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
];

/// Bumped by every copy in any app; cheap to poll.
pub fn change_count() -> isize {
    NSPasteboard::generalPasteboard().changeCount()
}

/// What's on the pasteboard now: files first, then a picture, then text. `None` when it's
/// empty, something else (a colour), or marked private.
pub fn read() -> Option<Copied> {
    autoreleasepool(|_| {
        let pb = NSPasteboard::generalPasteboard();
        let types: Vec<String> = pb.types()?.iter().map(|t| t.to_string()).collect();
        if types.iter().any(|t| PRIVATE.contains(&t.as_str())) { return None; }
        let has = |t: &NSPasteboardType| types.iter().any(|x| *x == t.to_string());
        if has(unsafe { NSPasteboardTypeFileURL }) {
            let urls: Vec<String> = pb.pasteboardItems()?.iter()
                .filter_map(|item| item.stringForType(unsafe { NSPasteboardTypeFileURL }))
                .map(|s| s.to_string())
                .filter(|s| s.starts_with("file://"))
                .collect();
            if !urls.is_empty() { return Some(Copied::Files(urls)); }
        }
        if has(unsafe { NSPasteboardTypePNG }) {
            if let Some(d) = pb.dataForType(unsafe { NSPasteboardTypePNG }) { return Some(Copied::Png(d.to_vec())); }
        }
        if has(unsafe { NSPasteboardTypeTIFF }) && !has(unsafe { NSPasteboardTypeString }) {
            // Screenshots and image editors offer TIFF; keep it as PNG, which previews everywhere.
            if let Some(png) = pb.dataForType(unsafe { NSPasteboardTypeTIFF }).and_then(|d| tiff_to_png(&d)) {
                return Some(Copied::Png(png));
            }
        }
        let text = pb.stringForType(unsafe { NSPasteboardTypeString })?.to_string();
        (!text.is_empty()).then_some(Copied::Text(text))
    })
}

fn tiff_to_png(tiff: &NSData) -> Option<Vec<u8>> {
    let rep = NSBitmapImageRep::imageRepWithData(tiff)?;
    let props = NSDictionary::new();
    let png = unsafe { rep.representationUsingType_properties(NSBitmapImageFileType::PNG, &props) }?;
    Some(png.to_vec())
}

/// Replace the pasteboard with an image (`png`, `jpeg`, … as the MIME subtype says).
pub fn write_image(bytes: &[u8], mime: &str) -> bool {
    autoreleasepool(|_| {
        let data = NSData::with_bytes(bytes);
        let pb = NSPasteboard::generalPasteboard();
        pb.clearContents();
        if mime == "image/png" { return pb.setData_forType(Some(&data), unsafe { NSPasteboardTypePNG }); }
        // Anything else goes through a bitmap rep as TIFF, AppKit's native picture type.
        match NSBitmapImageRep::imageRepWithData(&data).and_then(|r| r.TIFFRepresentation()) {
            Some(tiff) => pb.setData_forType(Some(&tiff), unsafe { NSPasteboardTypeTIFF }),
            None => false,
        }
    })
}

/// Replace the pasteboard with copied files (`file:///…` URLs), so Finder pastes the files.
pub fn write_files(urls: &[String]) -> bool {
    autoreleasepool(|_| {
        let items: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = urls.iter().map(|u| {
            let item = NSPasteboardItem::new();
            item.setString_forType(&NSString::from_str(u), unsafe { NSPasteboardTypeFileURL });
            ProtocolObject::from_retained(item)
        }).collect();
        let pb = NSPasteboard::generalPasteboard();
        pb.clearContents();
        pb.writeObjects(&NSArray::from_retained_slice(&items))
    })
}
